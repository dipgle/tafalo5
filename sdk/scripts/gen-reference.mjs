#!/usr/bin/env node
// Generate docs/reference.md from the SDK source, so the method reference
// cannot drift from the code.
//
//   node scripts/gen-reference.mjs           # (re)write docs/reference.md
//   node scripts/gen-reference.mjs --check   # exit 1 if docs/reference.md is stale
//
// For every client reachable from `new TFL5()` it lists each public method
// with its signature, the first paragraph of its doc comment, and the
// endpoint(s) it calls (string literals starting with "/" in its body).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "src");
const OUT = path.join(ROOT, "docs", "reference.md");
const check = process.argv.includes("--check");

const files = fs
  .readdirSync(SRC)
  .filter((f) => f.endsWith(".ts"))
  .map((f) => path.join(SRC, f));
const program = ts.createProgram(files, { target: ts.ScriptTarget.ES2021, module: ts.ModuleKind.ESNext });
const checker = program.getTypeChecker();

// class name -> ClassDeclaration
const classes = new Map();
for (const sf of program.getSourceFiles()) {
  if (!sf.fileName.startsWith(SRC)) continue;
  ts.forEachChild(sf, (n) => {
    if (ts.isClassDeclaration(n) && n.name) classes.set(n.name.text, { node: n, sf });
  });
}

const docOf = (node) => {
  const sym = node.name ? checker.getSymbolAtLocation(node.name) : undefined;
  const text = sym ? ts.displayPartsToString(sym.getDocumentationComment(checker)) : "";
  const first = text.split(/\n\s*\n/)[0] ?? "";
  return first.replace(/\s+/g, " ").trim();
};

const endpointsIn = (node) => {
  const out = new Set();
  const visit = (n) => {
    if ((ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n)) && /^\/[a-z_]/.test(n.text)) {
      out.add(n.text);
    } else if (ts.isTemplateExpression(n) && n.head.text.startsWith("/")) {
      let s = n.head.text;
      for (const span of n.templateSpans) s += `:${span.expression.getText().replace(/^.*\./, "")}` + span.literal.text;
      out.add(s);
    }
    ts.forEachChild(n, visit);
  };
  if (node.body) visit(node.body);
  return [...out];
};

const signatureOf = (m, sf) => {
  const params = m.parameters.map((p) => p.getText(sf).replace(/\s*=\s*[^,]+$/, (d) => d)).join(", ");
  const ret = m.type ? `: ${m.type.getText(sf)}` : "";
  const name = m.name.getText(sf);
  const kind = ts.isGetAccessor(m) ? "get " : "";
  return `${kind}${name}(${params})${ret}`.replace(/\s+/g, " ");
};

const isPublic = (m) =>
  !(ts.getCombinedModifierFlags(m) & (ts.ModifierFlags.Private | ts.ModifierFlags.Protected)) &&
  !m.name?.getText().startsWith("#");

function methodsOf(className) {
  const c = classes.get(className);
  if (!c) return [];
  const rows = [];
  for (const m of c.node.members) {
    if (!(ts.isMethodDeclaration(m) || ts.isGetAccessor(m)) || !isPublic(m)) continue;
    rows.push({ sig: signatureOf(m, c.sf), doc: docOf(m), eps: endpointsIn(m) });
  }
  return rows;
}

// Clients attached to TFL5: `readonly <prop>: <Class>` (+ nested readonly clients).
function attached(className) {
  const c = classes.get(className);
  const out = [];
  for (const m of c.node.members) {
    if (ts.isPropertyDeclaration(m) && m.type && ts.isTypeReferenceNode(m.type) && isPublic(m)) {
      const t = m.type.typeName.getText(c.sf);
      if (classes.has(t)) out.push({ prop: m.name.getText(c.sf), cls: t });
    }
  }
  return out;
}

const esc = (s) => s.replace(/\|/g, "\\|");
let md = `# API reference

<!-- GENERATED by scripts/gen-reference.mjs from src/ — do not edit by hand.
     Regenerate: npm run docs:reference · Check: npm run docs:check -->

Every method below is on a client reachable from \`const tfl5 = new TFL5(config)\`.
\`app_tid\` is filled in from \`tfl5.useApp(appTid)\` unless you pass one.
Guides: [getting started](getting-started.md) · [authentication](authentication.md) ·
[data](data.md) · [files and sites](files-and-sites.md) · [realtime](realtime.md) ·
[billing](billing.md) · [errors](errors.md).

`;

const section = (title, cls, prefix) => {
  const rows = methodsOf(cls);
  if (!rows.length) return;
  md += `## ${title}\n\n`;
  md += `| STT | Method | Endpoint | Description |\n|---|---|---|---|\n`;
  rows.forEach((r, i) => {
    const ep = r.eps.length ? r.eps.map((e) => `\`${e}\``).join("<br>") : "—";
    md += `| ${i + 1} | \`${esc(prefix + r.sig)}\` | ${esc(ep)} | ${esc(r.doc)} |\n`;
  });
  md += "\n";
};

section("TFL5 (root client)", "TFL5", "tfl5.");
const documented = new Map(); // class -> first property that documented it
const aliases = [];
for (const { prop, cls } of attached("TFL5")) {
  if (documented.has(cls)) {
    aliases.push(`\`tfl5.${prop}\` is the same client as \`tfl5.${documented.get(cls)}\``);
    continue;
  }
  documented.set(cls, prop);
  section(`tfl5.${prop} — ${cls}`, cls, `tfl5.${prop}.`);
  for (const sub of attached(cls)) section(`tfl5.${prop}.${sub.prop} — ${sub.cls}`, sub.cls, `tfl5.${prop}.${sub.prop}.`);
}
if (aliases.length) md += `## Aliases\n\nKept for code written against SDK 0.1.0:\n\n${aliases.map((a) => `- ${a}`).join("\n")}\n\n`;
section("tfl5.resource(ma) — ResourceClient", "ResourceClient", "tfl5.resource(ma).");
section("tfl5.resource(ma).hooks — HooksAccessor", "HooksAccessor", "hooks.");
section("tfl5.operator(opId) — OperatorClient", "OperatorClient", "tfl5.operator(opId).");
section("tfl5.durable.subscribe(...) — DurableSubscription", "DurableSubscription", "sub.");

const total = (md.match(/^\| \d+ \|/gm) ?? []).length;
md += `---\n\n${total} methods.\n`;

if (check) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== md) {
    console.error(`docs/reference.md is STALE vs src/ (${total} methods). Run: npm run docs:reference`);
    process.exit(1);
  }
  console.log(`docs/reference.md is current (${total} methods).`);
  process.exit(0);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, md);
console.log(`wrote docs/reference.md (${total} methods)`);
